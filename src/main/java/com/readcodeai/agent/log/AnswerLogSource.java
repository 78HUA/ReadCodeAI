package com.readcodeai.agent.log;

/**
 * 这次问答**是谁问的** —— 用户提问与评估跑题走的是同一条流水线，但账必须分开算。
 *
 * <p>为什么需要一个枚举而不是随手写个字符串：跑一次评估集就是 200+ 行流水，
 * 页面上的「累计问答」如果把它们算进去，就不再是"这个服务被用了多少次"了。
 * 用枚举把这件事钉在类型上，调用方拼错字符串也编译不过。
 */
public enum AnswerLogSource {
    /** 用户（或前端）真的问了这个问题。 */
    USER,
    /** 评估集 / 对比实验自己跑的题（题目不落库，所以只看这一列就能区分）。 */
    EVAL
}
