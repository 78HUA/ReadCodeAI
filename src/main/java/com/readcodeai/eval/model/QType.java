package com.readcodeai.eval.model;

/**
 * 评估题型。
 *
 * <p>这五种题型的共同点是：**正确答案是程序算出来的，不是人标的** ——
 * 所以能自动出题、自动判卷，而且不存在「用模型判模型」的循环依赖。
 */
public enum QType {

    /** 方法定义在哪 → 比 文件 + 起始行 */
    LOCATE,
    /** 谁调用了它 → 比调用点集合 */
    CALLERS,
    /** 它调用了谁 → 比被调用者的定义位置集合 */
    CALLEES,
    /** 这个类有哪些方法/字段 → 比成员集合 */
    STRUCTURE,
    /** 这个接口有哪些实现类 → 比实现类集合 */
    IMPLEMENTS
}
